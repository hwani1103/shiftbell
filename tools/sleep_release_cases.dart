// Shared deterministic cases, run on the host and on the Android device.
// This file is a test tool, never imported by the production entry point.
import 'package:shiftbell/models/shift_schedule.dart';
import 'package:shiftbell/models/shift_time_range.dart';
import 'package:shiftbell/models/sleep_record.dart';
import 'package:shiftbell/services/condition/shift_pattern_analyzer.dart';
import 'package:shiftbell/services/condition/sleep_day_slots.dart';
import 'package:shiftbell/services/condition/sleep_by_category_stats.dart';

Map<String, Object?> runSleepReleaseCases() {
  final results = <Map<String, Object?>>[];
  final errors = <String>[];
  void check(String name, Object? actual, Object? expected) {
    final passed = actual == expected;
    results.add({'case': name, 'actual': actual, 'expected': expected, 'pass': passed});
    if (!passed) errors.add(name);
  }
  final anchor = DateTime(2026, 10, 10);
  const pattern = ['Off', 'Night', 'Night', 'Off', 'Day', 'Off', 'Evening', 'Off'];
  final analyzer = ShiftPatternAnalyzer(
    schedule: ShiftSchedule(isRegular: true, pattern: pattern, todayIndex: 0,
      startDate: anchor, shiftTypes: pattern.toSet().toList()),
    shiftTimes: {
      'Day': const ShiftTimeRange(shiftName: 'Day', startMinutes: 420, endMinutes: 1140),
      'Night': const ShiftTimeRange(shiftName: 'Night', startMinutes: 1140, endMinutes: 420),
      'Evening': const ShiftTimeRange(shiftName: 'Evening', startMinutes: 900, endMinutes: 1380),
    },
  );
  // start day/hour/minute, elapsed minutes, attributed October day, main/nap.
  // Expected values are an explicit policy ledger, not generated by the engine.
  const cases = <(int, int, int, int, int, String)>[
    (10, 23, 0, 480, 10, 'main'), // night before the first night shift
    (11, 0, 30, 390, 10, 'main'),
    (11, 5, 59, 120, 10, 'main'),
    (11, 6, 0, 120, 11, 'nap'),
    (11, 8, 0, 300, 11, 'nap'),
    (11, 13, 0, 300, 11, 'nap'),
    (11, 18, 0, 60, 11, 'nap'),
    (11, 19, 0, 360, 11, 'nap'),
    (11, 22, 0, 180, 11, 'nap'),
    (12, 0, 0, 120, 11, 'nap'),
    (12, 5, 59, 121, 11, 'nap'), // one-minute work overlap before grace end
    (12, 6, 0, 120, 11, 'main'),
    (12, 6, 50, 240, 11, 'main'),
    (12, 7, 0, 119, 11, 'nap'),
    (12, 7, 0, 120, 11, 'main'),
    (12, 8, 0, 300, 11, 'main'),
    (12, 10, 0, 298, 11, 'main'), // midpoint 12:29
    (12, 10, 0, 300, 12, 'nap'), // midpoint exactly 12:30
    (12, 10, 0, 302, 12, 'nap'),
    (12, 12, 0, 390, 12, 'nap'),
    (12, 14, 0, 180, 12, 'nap'),
    (12, 17, 0, 120, 12, 'nap'),
    (12, 23, 0, 180, 12, 'nap'),
    (13, 0, 0, 120, 12, 'nap'),
    (13, 6, 0, 120, 12, 'main'),
    (13, 7, 0, 360, 12, 'main'),
    (13, 14, 0, 180, 12, 'main'), // day off: boundary remains 21:00
    (13, 20, 0, 118, 12, 'nap'),
    (13, 20, 0, 120, 13, 'main'), // midpoint exactly 21:00
    (13, 20, 30, 510, 13, 'main'),
    (13, 23, 0, 420, 13, 'main'),
    (14, 0, 30, 330, 13, 'main'),
    (14, 8, 0, 360, 14, 'nap'),
    (14, 19, 0, 120, 14, 'main'),
    (15, 0, 30, 330, 14, 'main'),
    (15, 5, 59, 120, 14, 'main'),
    (15, 6, 0, 120, 15, 'main'),
    (15, 14, 0, 119, 15, 'nap'),
    (15, 14, 0, 120, 15, 'main'),
    (16, 16, 0, 240, 16, 'nap'),
    (16, 23, 0, 420, 16, 'main'),
  ];
  for (var i = 0; i < cases.length; i++) {
    final c = cases[i];
    final start = DateTime(2026, 10, c.$1, c.$2, c.$3);
    final record = SleepRecord(id: i + 1, start: start,
      end: start.add(Duration(minutes: c.$4)), source: SleepSource.manual,
      status: SleepStatus.confirmed);
    final slots = buildSleepDaySlots(records: [record], from: DateTime(2026, 10, 8),
      to: DateTime(2026, 10, 18), analyzer: analyzer);
    final filled = slots.where((s) => !s.isEmpty).toList();
    check('attribution ' + i.toString(), filled.length, 1);
    if (filled.length == 1) {
      check('date ' + i.toString(), filled.single.date.day, c.$5);
      check('slot ' + i.toString(), filled.single.mainSleep == null ? 'nap' : 'main', c.$6);
      check('minutes ' + i.toString(),
        (filled.single.mainSleep?.durationMinutes ?? 0) + filled.single.napMinutes, c.$4);
    }
  }
  final offAnalyzer = ShiftPatternAnalyzer(schedule: ShiftSchedule(isRegular: true,
    pattern: const ['Off'], todayIndex: 0, startDate: anchor, shiftTypes: const ['Off']), shiftTimes: const {});
  final records = <SleepRecord>[];
  for (var day = 1; day <= 3; day++) {
    for (final part in [(8, 30), (12, 40), (16, 50), (22, 420)]) {
      final start = DateTime(2026, 10, day, part.$1);
      records.add(SleepRecord(id: records.length + 1, start: start,
        end: start.add(Duration(minutes: part.$2)), source: SleepSource.manual,
        status: SleepStatus.confirmed));
    }
  }
  final slots = buildSleepDaySlots(records: records, from: DateTime(2026, 10, 1),
    to: DateTime(2026, 10, 3), analyzer: offAnalyzer);
  check('all three naps retained', slots.first.allNaps.length, 3);
  check('longest eligible sleep is main', slots.first.mainSleep?.durationMinutes, 420);
  final averages = buildSleepCategoryAverages(records: records, analyzer: offAnalyzer,
    now: DateTime(2026, 10, 10));
  check('average sample excludes unrecorded days', averages.single.sampleDays, 3);
  check('average main', averages.single.averageMainMinutes, 420);
  check('average includes every nap', averages.single.averageNapMinutes, 120);
  check('average total', averages.single.averageMinutes, 540);
  final pending = SleepRecord(start: DateTime(2026, 10, 4, 22), end: DateTime(2026, 10, 5, 6),
    source: SleepSource.autoDetected, status: SleepStatus.pendingConfirmation);
  final withPending = buildSleepCategoryAverages(records: [...records, pending],
    analyzer: offAnalyzer, now: DateTime(2026, 10, 10));
  check('pending does not change sample', withPending.single.sampleDays, 3);
  check('pending does not change average', withPending.single.averageMinutes, 540);
  return {'scenarioCount': cases.length + 2, 'checkCount': results.length,
    'errors': errors, 'results': results};
}
