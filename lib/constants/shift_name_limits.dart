// ⭐ 영어 현지화 결정 사항(교대시계_영어화_현지화_보고서_영문판.md 2-2번 참고).
// 예전엔 "근무명 최대 4글자"가 onboarding_screen.dart/settings_tab.dart 등
// 여러 곳에 리터럴(4)로 흩어져 있었음. 한국어 4글자("주간","야간","오전","오후",
// "휴무")는 의미가 꽉 차지만 영어는 4글자로 거의 아무것도 못 씀(예: "Night"도
// 5글자, "Morning"은 7글자, "Afternoon"은 9글자).
//
// 왜 10인가: 보고서는 "최소 12~15글자" 권장이지만, 이 앱의 근무명 뱃지는 달력
// 셀 폭이 유한한 자리(요일 칸 하나)에 들어가는 짧은 라벨이라는 기존 디자인
// 전제 자체가 있어서, 완전히 그 권장치까지 열면 뱃지 레이아웃이 거의 항상
// FittedBox로 잔뜩 축소된 상태로만 보이게 됨(가독성 오히려 악화). 실사용
// 영어 근무명 대부분("Morning"/"Afternoon"/"Evening"/"Overnight"/"Standby"
// 등)이 10글자 이내라 대다수 케이스를 커버하면서, 뱃지가 과도하게 안 작아지는
// 절충점으로 10을 택함. 동시에 실제 화면(달력 셀 뱃지, 근무 칩 등)은 이 상한을
// 넘는 텍스트가 들어와도 안 잘리고 자동으로 줄어들도록 FittedBox 처리를
// 같이 적용함(calendar_tab.dart/calendar_theme_lab_screen.dart) - 그래서 이
// 상수를 나중에 더 올리더라도 레이아웃이 깨지지 않음.
//
// 한국어/영어 공통 상한(로케일별로 다르게 두지 않음) - 로케일이 나뉘어도
// 근무명 자체는 사용자가 그 시점 기기 언어로 자유롭게 입력하는 텍스트라,
// 상한만 넉넉하게 두고 실제 표시는 FittedBox가 흡수하는 쪽이 더 단순하고
// 안전함(로케일별로 다른 상한을 두면 언어를 나중에 바꿨을 때 기존에 입력된
// 근무명이 새 상한을 초과하는 경우까지 신경 써야 해서 오히려 더 위험함).
const int kMaxShiftNameLength = 10;
