// ⭐ 알람 개수/갱신주기 관련 상수를 한 곳에 모음. 예전엔 "근무당 알람 3개",
// "10일치 갱신"이 여러 파일에 리터럴(3, 10)로 흩어져 있어서 값을 바꾸려면
// 전부 찾아 고쳐야 했음 - 값 자체가 바뀔 일이 (드물게라도) 있는 숫자라 상수로
// 뺌. Kotlin 네이티브 쪽의 진짜 갱신 루프(AlarmRefreshEngine.kt의
// DAYS_AHEAD)는 별도 파일이라 이 상수를 직접 참조할 순 없지만, 값은 반드시
// 이 파일과 같게 유지해야 함 - 바뀌면 두 곳 다 같이 고칠 것.
//
// ⭐ 2026-08-12 - 사용자 피드백("하루 3개는 아쉽다")으로 3→5로 상향함. 왜 5인지
// (7이 아니라): AlarmManager 자체엔 UID당 최대 500개 동시 등록 한도가 있어서
// (AOSP AlarmManagerService의 MAX_ALARMS_PER_UID) 5×10=50이든 7×10=70이든
// OS 등록 한도 관점에서는 사실상 차이가 없음 - 진짜 병목이 아님. 실제 신뢰성
// 리스크는 "하루에 폰이 실제로 몇 번 깨어나는가"(배터리 소모, 삼성/샤오미 등
// 제조사 백그라운드 킬러에 찍힐 확률)이고, 이건 갱신주기(DAYS_AHEAD)가 아니라
// 오직 하루 개수에만 비례함 - 그래서 갱신주기는 굳이 줄일 이유가 없어 10일
// 그대로 유지하고(줄이면 갱신 실패 상황에 대한 완충 여유만 줄어듦), 하루
// 개수만 사용자 요청 범위(5~7)의 보수적인 쪽인 5로 올림. 나중에 실기기에서
// 5가 문제없이 안정적으로 확인되면 7로 더 올리는 것도 여전히 안전함(50→70도
// 500 한도에 비하면 여유가 큼) - 이 상수만 바꾸면 됨.

/// 근무 하나당 등록 가능한 고정 알람 템플릿 최대 개수. 온보딩/설정 탭 둘 다 이
/// 값을 씀.
/// ⭐ 2026-08-25 - 전날/당일/다음날(day_offset) 지원 이후로는 "하루 최대 알람
/// 개수"와 완전히 같지 않게 됨 - 하루의 알람은 그날 배정된 근무(당일)뿐 아니라
/// 전날/다음날 근무의 오프셋 알람도 받을 수 있어서, 이론상 하루에 최대
/// 3×kMaxAlarmTemplatesPerShift(=15)까지 몰릴 수 있음(각 근무가 전부 다른
/// 오프셋에 5개씩 몰아 설정하는 극단적 경우). AlarmManager의 UID당 500개 한도
/// 대비 10일×15 = 150이라 여전히 크게 여유 있어 문제는 없음(alarm_generation_
/// service.dart 파일 상단 주석 참고) - 다만 "보통 하루 하나"라는 예전 가정이
/// 더는 항상 성립하지 않는다는 점만 기억할 것.
const int kMaxAlarmTemplatesPerShift = 5;

/// 알람을 미리 생성해두고 유지하는 롤링 윈도우(일). Kotlin
/// AlarmRefreshEngine.kt의 DAYS_AHEAD와 반드시 같은 값을 유지할 것.
const int kAlarmRefreshWindowDays = 10;
