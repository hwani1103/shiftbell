def existing_texts():
    texts = set()
    for fn in ["pilot_dataset.jsonl", "boundary_cases.jsonl", "eval_holdout.jsonl"]:
        with open(DATA_DIR / fn, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                texts.add(json.loads(line)["text"])
    return texts


def main():
    seen = existing_texts()
    added = []
    for label, texts in TERSE_EXAMPLES.items():
        for text in texts:
            if text in seen:
                continue
            seen.add(text)
            added.append({"text": text, "label": label})

    with open(PILOT_PATH, "a", encoding="utf-8") as f:
        for row in added:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"{len(added)}개 추가")
    from collections import Counter
    print(Counter(r["label"] for r in added))


if __name__ == "__main__":
    main()
